/// Build script: embeds the @rodeo shims and the runtime adapters, generating
/// adapters_gen.rs.
///
/// Layout — each alias is a folder that mirrors the module tree of the
/// runtime it stands in for:
///   rodeo-pkg/rodeo/shims/**                   →  @rodeo (always available)
///   rodeo-adapters/<adapter>/<alias>/**        →  @<alias>, when `--adapter <adapter>`
///   rodeo-adapters/_bridge/**                  →  @rodeo-bridge, with any adapter
///
/// e.g. rodeo-adapters/lute/std/path/init.luau answers require("@std/path").
/// Only `.luau` files are embedded; files next to the alias folders (README,
/// LICENSE) are not.

use std::env;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

/// (path relative to the alias folder with `/` separators, absolute path)
type AliasFiles = Vec<(String, PathBuf)>;

fn main() {
    // Proto compilation is in rodeo-proto crate.

    let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let out_dir = env::var("OUT_DIR").unwrap();
    let out_path = PathBuf::from(&out_dir).join("adapters_gen.rs");

    let rodeo_shims_dir = fs::canonicalize(Path::new(&manifest_dir).join("../rodeo-pkg/rodeo/shims"))
        .expect("rodeo-pkg/rodeo/shims directory not found");
    println!("cargo:rerun-if-changed={}", rodeo_shims_dir.display());
    let rodeo_files = scan_alias_dir(&rodeo_shims_dir);

    let adapters_dir = fs::canonicalize(Path::new(&manifest_dir).join("../rodeo-adapters"))
        .expect("rodeo-adapters directory not found");
    println!("cargo:rerun-if-changed={}", adapters_dir.display());

    let bridge_files = scan_alias_dir(&adapters_dir.join("_bridge"));

    let mut adapters: Vec<(String, Vec<(String, AliasFiles)>)> = Vec::new();
    for adapter_dir in sorted_dirs(&adapters_dir) {
        let adapter = dir_name(&adapter_dir);
        if adapter.starts_with('_') {
            continue;
        }
        let aliases: Vec<(String, AliasFiles)> = sorted_dirs(&adapter_dir)
            .into_iter()
            .map(|alias_dir| (format!("@{}", dir_name(&alias_dir)), scan_alias_dir(&alias_dir)))
            .collect();
        adapters.push((adapter, aliases));
    }

    let mut out = fs::File::create(&out_path).expect("cannot create adapters_gen.rs");
    writeln!(out, "// AUTO-GENERATED by build.rs — do not edit\n").unwrap();
    writeln!(out, "static RODEO: AliasTree = {};\n", alias_tree("@rodeo", &rodeo_files)).unwrap();
    writeln!(out, "static BRIDGE: AliasTree = {};\n", alias_tree("@rodeo-bridge", &bridge_files)).unwrap();
    writeln!(out, "static ADAPTERS: &[Adapter] = &[").unwrap();
    for (adapter, aliases) in &adapters {
        writeln!(out, "    Adapter {{ name: {adapter:?}, aliases: &[").unwrap();
        for (alias, files) in aliases {
            writeln!(out, "        {},", alias_tree(alias, files)).unwrap();
        }
        writeln!(out, "    ] }},").unwrap();
    }
    writeln!(out, "];").unwrap();
}

fn alias_tree(alias: &str, files: &AliasFiles) -> String {
    let entries: Vec<String> = files
        .iter()
        .map(|(rel, abs)| {
            // Forward slashes keep include_str! paths valid on Windows.
            let abs = abs.display().to_string().replace('\\', "/");
            format!("({rel:?}, include_str!({abs:?}))")
        })
        .collect();
    format!("AliasTree {{ alias: {alias:?}, files: &[{}] }}", entries.join(", "))
}

fn dir_name(dir: &Path) -> String {
    dir.file_name().unwrap().to_string_lossy().to_string()
}

fn sorted_dirs(dir: &Path) -> Vec<PathBuf> {
    let mut dirs: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|_| panic!("cannot read {}", dir.display()))
        .filter_map(|e| e.ok())
        .filter(|e| e.file_type().map(|ft| ft.is_dir()).unwrap_or(false))
        .map(|e| e.path())
        .collect();
    dirs.sort();
    dirs
}

/// Every `.luau` file under `root`, keyed by its path relative to `root`.
fn scan_alias_dir(root: &Path) -> AliasFiles {
    fn walk(root: &Path, dir: &Path, files: &mut AliasFiles) {
        let mut entries: Vec<PathBuf> = fs::read_dir(dir)
            .unwrap_or_else(|_| panic!("cannot read {}", dir.display()))
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .collect();
        entries.sort();
        for path in entries {
            if path.is_dir() {
                walk(root, &path, files);
            } else if path.extension().is_some_and(|ext| ext == "luau") {
                let rel = path.strip_prefix(root).unwrap();
                let rel = rel.components().map(|c| c.as_os_str().to_string_lossy()).collect::<Vec<_>>().join("/");
                let abs = fs::canonicalize(&path).unwrap();
                println!("cargo:rerun-if-changed={}", abs.display());
                files.push((rel, abs));
            }
        }
    }
    let mut files = Vec::new();
    walk(root, root, &mut files);
    files
}
